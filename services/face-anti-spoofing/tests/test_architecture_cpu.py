import torch


ROOT = Path(__file__).resolve().parents[1]
COMMIT = "b6d5f04ad78778917853b25c778acef6d5626d15"
SOURCE_SHA256 = "e498c4ec5e1ddfaba62b941a126c19d65aa564999f3309661fe43ee8bf38acd7"
INPUT_SEED = 20261012
KERNEL = ((80 + 15) // 16, (80 + 15) // 16)
OBSERVATIONS = {}
OLD_THREADS = None

spec = importlib.util.spec_from_file_location("minivision_architecture_reference", ROOT / "reference/MiniFASNet.py")
architecture = importlib.util.module_from_spec(spec)
spec.loader.exec_module(architecture)


def setUpModule():
    global OLD_THREADS
    if torch.version.cuda is not None or not torch.__version__.endswith("+cpu"):
        raise RuntimeError("Stage 9E requires the existing CPU environment")
    if not Path(torch.__file__).resolve().is_relative_to(Path(sys.prefix).resolve()):
        raise RuntimeError("Torch is outside the active venv")
    if sys.prefix == sys.base_prefix:
        raise RuntimeError("Stage 9E must not use global Python")
    OLD_THREADS = torch.get_num_threads()
    torch.set_num_threads(1)
    OBSERVATIONS.clear()


def tearDownModule():
    if OLD_THREADS is not None:
        torch.set_num_threads(OLD_THREADS)


def synthetic_input():
    # Channel indices are B,G,R. Unnormalised synthetic byte-range pixels.
    generator = torch.Generator(device="cpu").manual_seed(INPUT_SEED)
    return torch.randint(0, 256, (1, 3, 80, 80), generator=generator, dtype=torch.int32).to(torch.float32)


def new_model(name, seed, drop_p):
    # Restore caller RNG state; all initialisation is local and reproducible.
    with torch.random.fork_rng(devices=[]):
        torch.manual_seed(seed)
        model = getattr(architecture, name)(embedding_size=128, conv6_kernel=KERNEL,
                                             drop_p=drop_p, num_classes=3, img_channel=3)
    return model.to(device="cpu", dtype=torch.float32).eval()


def safe_load_synthetic_checkpoint(model, path):
    # Used only on checkpoints freshly generated by tests in their own temp dir.
    state = torch.load(path, map_location="cpu", weights_only=True)
    return model.load_state_dict(state, strict=True)


class _ArchitectureChecks:
    NAME = ""
    MODEL_SEED = 0
    DROP_P = 0.0

    def build(self, seed=None):
        return new_model(self.NAME, self.MODEL_SEED if seed is None else seed, self.DROP_P)

    def test_explicit_inference_configuration(self):
        model = self.build()
        self.assertEqual(KERNEL, (5, 5))
        self.assertEqual(model.conv_6_dw.conv.kernel_size, (5, 5))
        self.assertEqual(model.conv1.conv.in_channels, 3)
        self.assertEqual(model.linear.out_features, 128)
        self.assertEqual(model.prob.out_features, 3)
        self.assertEqual(model.drop.p, self.DROP_P)
        self.assertTrue(all(not module.training for module in model.modules()))
        self.assertTrue(all(p.device.type == "cpu" and p.dtype == torch.float32 for p in model.parameters()))

    def test_forward_logits_and_explicit_softmax(self):
        model = self.build()
        pixels = synthetic_input()
        original = pixels.clone()
        self.assertEqual(tuple(pixels.shape), (1, 3, 80, 80))
        self.assertEqual(pixels.dtype, torch.float32)
        self.assertEqual(float(pixels.min()), 0.0)
        self.assertEqual(float(pixels.max()), 255.0)
        with torch.no_grad():
            started = perf_counter()
            logits = model(pixels)
            elapsed_ms = (perf_counter() - started) * 1000
            probabilities = torch.softmax(logits, dim=1)
        self.assertEqual(tuple(logits.shape), (1, 3))
        self.assertEqual(tuple(probabilities.shape), (1, 3))
        self.assertTrue(bool(torch.isfinite(logits).all()))
        self.assertTrue(bool(torch.isfinite(probabilities).all()))
        self.assertTrue(bool(((probabilities >= 0) & (probabilities <= 1)).all()))
        self.assertTrue(torch.allclose(probabilities.sum(dim=1), torch.ones(1), rtol=0, atol=1e-6))
        self.assertFalse(logits.requires_grad)
        self.assertIsNone(logits.grad_fn)
        self.assertTrue(all(p.grad is None for p in model.parameters()))
        self.assertTrue(torch.equal(pixels, original))
        OBSERVATIONS[self.NAME] = {
            "status": "PASS", "model_seed": self.MODEL_SEED, "input_seed": INPUT_SEED,
            "config": {"embedding_size": 128, "conv6_kernel": [5, 5], "drop_p": self.DROP_P,
                       "num_classes": 3, "img_channel": 3},
            "input": {"shape": [1, 3, 80, 80], "dtype": "float32", "color": "BGR", "range": [0, 255]},
            "logits_shape": [1, 3], "logits_finite": True, "softmax_dim": 1,
            "softmax_finite_and_normalized": True, "eval": True, "no_grad": True,
            "forward_ms": elapsed_ms, "forward_timing_scope": "single_synthetic_forward_no_explicit_warmup_not_benchmark",
            "torch_threads": torch.get_num_threads(), "prediction_generated": False,
        }

    def test_same_initialisation_seed_reproduces_state(self):
        left, right = self.build(), self.build()
        left_state, right_state = left.state_dict(), right.state_dict()
        self.assertTrue(left_state.keys() == right_state.keys())
        self.assertTrue(all(torch.equal(left_state[k], right_state[k]) for k in left_state),
                        "Synthetic state differs for the same seed")

    def test_safe_strict_state_dict_round_trip_and_cleanup(self):
        original, restored = self.build(), self.build(seed=self.MODEL_SEED + 100)
        with tempfile.TemporaryDirectory(prefix="pad-stage9e-") as directory:
            temporary = Path(directory)
            checkpoint = temporary / "synthetic-state.pt"
            torch.save(original.state_dict(), checkpoint)
            outcome = safe_load_synthetic_checkpoint(restored, checkpoint)
            self.assertEqual(outcome.missing_keys, [])
            self.assertEqual(outcome.unexpected_keys, [])
            original_state, restored_state = original.state_dict(), restored.state_dict()
            self.assertTrue(all(torch.equal(original_state[k], restored_state[k]) for k in original_state),
                            "Synthetic state round-trip differs")
            with torch.no_grad():
                expected, actual = original(synthetic_input()), restored(synthetic_input())
            self.assertTrue(torch.equal(expected, actual), "Synthetic forward differs after round-trip")
        self.assertFalse(temporary.exists(), "Synthetic checkpoint directory was not removed")

    def assert_bad_state_rejected(self, mutation, expected_error):
        model = self.build()
        state = model.state_dict()
        mutation(state)
        with tempfile.TemporaryDirectory(prefix="pad-stage9e-") as directory:
            temporary = Path(directory)
            checkpoint = temporary / "invalid-synthetic-state.pt"
            torch.save(state, checkpoint)
            with self.assertRaisesRegex(RuntimeError, expected_error):
                safe_load_synthetic_checkpoint(model, checkpoint)
        self.assertFalse(temporary.exists(), "Invalid synthetic checkpoint directory was not removed")

    def test_missing_key_rejected(self):
        self.assert_bad_state_rejected(lambda state: state.pop("prob.weight"), "Missing key")

    def test_unexpected_key_rejected(self):
        self.assert_bad_state_rejected(lambda state: state.update({"synthetic.unexpected": torch.zeros(1)}),
                                       "Unexpected key")

    def test_wrong_shape_rejected(self):
        self.assert_bad_state_rejected(lambda state: state.update({"prob.weight": torch.zeros((4, 128))}),
                                       "size mismatch")


