class ArchitectureSourceTests(unittest.TestCase):
    def test_pinned_source_and_license_retained(self):
        meta = json.loads((ROOT / "reference/MiniFASNet.sources.json").read_text(encoding="utf-8"))
        source = (ROOT / "reference/MiniFASNet.py").read_text(encoding="utf-8")
        self.assertEqual(meta["commit"], COMMIT)
        self.assertEqual(meta["upstream_path"], "src/model_lib/MiniFASNet.py")
        self.assertIn("/" + COMMIT + "/", meta["source"])
        self.assertEqual(meta["sha256_lf_utf8"], SOURCE_SHA256)
        self.assertEqual(hashlib.sha256(source.encode("utf-8")).hexdigest(), SOURCE_SHA256)
        self.assertIn("Apache License", (ROOT / "reference/LICENSE").read_text(encoding="utf-8"))


class _RecordingResult(unittest.TextTestResult):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.records = []

    def addSuccess(self, test):
        super().addSuccess(test)
        self.records.append({"id": test.id(), "status": "PASS"})

    def addFailure(self, test, err):
        super().addFailure(test, err)
        self.records.append({"id": test.id(), "status": "FAIL", "error_type": err[0].__name__})

    def addError(self, test, err):
        super().addError(test, err)
        self.records.append({"id": test.id(), "status": "ERROR", "error_type": err[0].__name__})

    def addSkip(self, test, reason):
        super().addSkip(test, reason)
        self.records.append({"id": test.id(), "status": "SKIP"})


def main(argv=None):
    parser = argparse.ArgumentParser(description="Architecture compatibility only; no pretrained weights or PAD predictions.")
    parser.add_argument("--output", type=Path, help="Optional safe metadata JSON; existing output refused")
    args = parser.parse_args(argv)
    if args.output is not None and args.output.exists():
        parser.error("Output already exists; refusing overwrite")
    started_at = datetime.now(timezone.utc).isoformat()
    suite = unittest.defaultTestLoader.loadTestsFromModule(sys.modules[__name__])
    result = unittest.TextTestRunner(verbosity=2, resultclass=_RecordingResult).run(suite)
    if args.output is not None:
        architecture_results = {}
        for name in ("MiniFASNetV2", "MiniFASNetV1SE"):
            checks = [r for r in result.records if "." + name + "Tests." in r["id"]]
            architecture_results[name] = {
                **OBSERVATIONS.get(name, {}),
                "status": "PASS" if len(checks) == 7 and all(r["status"] == "PASS" for r in checks) else "FAIL_OR_INCOMPLETE",
                "checks": checks,
            }
        evidence = {
            "stage": "9E", "started_at": started_at, "completed_at": datetime.now(timezone.utc).isoformat(),
            "upstream_commit": COMMIT, "source_sha256_lf_utf8": SOURCE_SHA256,
            "runtime": {"python": platform.python_version(), "torch": torch.__version__,
                        "os": platform.system(), "bits": struct.calcsize("P") * 8, "device": "cpu",
                        "cuda_version": torch.version.cuda, "venv": ".cache/face-anti-spoofing-cpu"},
            "tests": {"run": result.testsRun, "pass": sum(r["status"] == "PASS" for r in result.records),
                      "skip": len(result.skipped), "fail": len(result.failures), "error": len(result.errors),
                      "records": result.records},
            "architectures": architecture_results,
            "state_dict_policy": {"weights_only": True, "map_location": "cpu", "strict": True,
                                  "unsafe_fallback": False, "temporary_checkpoints_only": True},
            "scope": {"synthetic_inputs": True, "pretrained_weights_loaded": False,
                      "detector_loaded": False, "training": False, "predictions_generated": False,
                      "pad_evaluation": False},
        }
        with args.output.open("x", encoding="utf-8", newline="\n") as handle:
            json.dump(evidence, handle, indent=2, allow_nan=False)
            handle.write("\n")
    return int(not result.wasSuccessful())


if __name__ == "__main__":
    raise SystemExit(main())
